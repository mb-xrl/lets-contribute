/** Stable icon per tag, so the same tag always renders the same glyph. */
export function iconForTag(tag: string): IconName {
  const key = tag.trim().toLowerCase();
  if (tagIcons[key]) return tagIcons[key];
  let hash = 0;
  for (let i = 0; i < key.length; i += 1) hash = (hash * 31 + key.charCodeAt(i)) % 9973;
  return fallbackIcons[hash % fallbackIcons.length];
}
